/// Covers [IComputedUnionColumnUpgrade], which brings the indexes for union-typed properties in an existing database in line with the current DDL.
///
/// The reference for what the database must look like is the current DDL, as generated by [TableDdl].
/// Tests that modify the schema of the test database reset it to the current DDL after they run,
/// as the test database is shared with other tests.
///
/// Changes to the members of a union type are simulated by replacing the index (and, for SQL Server, the computed column) for `TgBogie.location`
/// with one whose expression lists different members, as it would after the members of [TgBogieLocation] change.
///
public class ComputedUnionColumnUpgradeTest extends AbstractDaoTestCase {

    private static final String
            BOGIE_TABLE = "TGBOGIE_",
            BOGIE_LOCATION_COLUMN = "LOCATION_",
            BOGIE_LOCATION_INDEX = "I_TGBOGIE__LOCATION_",
            REMOVED_MEMBER_COLUMN = "LOCATION__REMOVEDMEMBER";

    /// Matches a statement that creates an index, capturing the index name and the table name.
    ///
    private static final Pattern CREATE_INDEX = Pattern.compile("CREATE INDEX (?:IF NOT EXISTS )?(\\S+) ON ([^\\s(]+)");

    /// Matches a statement that drops an index, capturing the index name.
    ///
    private static final Pattern DROP_INDEX = Pattern.compile("DROP INDEX (?:IF EXISTS )?(\\w+)");

    private final IComputedUnionColumnUpgrade upgrade = getInstance(IComputedUnionColumnUpgrade.class);
    private final DbVersion dbVersion = getInstance(IDbVersionProvider.class).dbVersion();

    @After
    public void restoreSchema() {
        resetUnionIndexToCurrentDdl();
    }

    // :::::::::::::::::::::::: Upgrade of a database created before union indexes ::::::::::::::::::::::::

    @Test
    @WithDbVersion({POSTGRESQL, MSSQL})
    public void upgrade_of_a_union_typed_property_restores_the_definition_produced_by_the_current_DDL() {
        final var definitionFromDdl = unionIndexDefinition();
        assertThat(definitionFromDdl).isNotEmpty();

        dropUnionIndex();
        assertThat(unionIndexDefinition()).isEmpty();

        exec(upgrade.createSql().property(TgBogie.class, TgBogie.LOCATION));

        assertThat(unionIndexDefinition()).isEqualTo(definitionFromDdl);
    }

    @Test
    @WithDbVersion({POSTGRESQL, MSSQL})
    public void upgrade_of_a_union_typed_property_can_be_rerun() {
        final var definitionFromDdl = unionIndexDefinition();

        dropUnionIndex();
        final var sql = upgrade.createSql().property(TgBogie.class, TgBogie.LOCATION);
        exec(sql);
        exec(sql);

        assertThat(unionIndexDefinition()).isEqualTo(definitionFromDdl);
    }

    @Test
    @WithDbVersion({POSTGRESQL, MSSQL})
    public void upgrade_of_the_whole_domain_covers_exactly_the_union_indexes_of_the_current_DDL_and_changes_nothing_in_an_up_to_date_database() {
        final var unionIndexesFromDdl = unionIndexNamesInDatabase();
        assertThat(unionIndexesFromDdl).contains(BOGIE_LOCATION_INDEX);

        final var sql = upgrade.createSql().allInDomain();
        assertThat(createdIndexes(sql).keySet()).isEqualTo(unionIndexesFromDdl);

        exec(sql);
        assertThat(unionIndexNamesInDatabase()).isEqualTo(unionIndexesFromDdl);
    }

    @Test
    @WithDbVersion({POSTGRESQL, MSSQL})
    public void upgrade_of_specific_entity_types_is_limited_to_their_tables() {
        assertThat(createdIndexes(upgrade.createSql().propertiesOf(List.of(TgBogie.class))))
                .containsExactly(Map.entry(BOGIE_LOCATION_INDEX, BOGIE_TABLE));
    }

    @Test
    @WithDbVersion({POSTGRESQL, MSSQL})
    public void upgrade_of_a_property_that_is_not_union_typed_is_rejected() {
        assertThatThrownBy(() -> upgrade.createSql().property(TgBogie.class, TgBogie.BOGIE_CLASS))
                .isInstanceOf(InvalidArgumentException.class)
                .hasMessageContaining(TgBogie.BOGIE_CLASS);
    }

    // :::::::::::::::::::::::: Changes to the members of a union type ::::::::::::::::::::::::

    @Test
    @WithDbVersion({POSTGRESQL, MSSQL})
    public void drop_and_create_scripts_for_a_union_type_cover_all_its_persistent_properties_and_no_others() {
        final var expected = unionIndexNamesForPropertiesOfType(UnionEntity.class);
        assertThat(expected).hasSizeGreaterThan(1);

        assertThat(createdIndexes(upgrade.createSql().propertiesWithType(UnionEntity.class)).keySet()).isEqualTo(expected);
        assertThat(droppedIndexes(upgrade.dropSql().propertiesWithType(UnionEntity.class))).isEqualTo(expected);
    }

    @Test
    @WithDbVersion({POSTGRESQL, MSSQL})
    public void after_a_member_is_added_the_upgrade_does_not_help_but_drop_and_create_scripts_restore_the_definition_produced_by_the_current_DDL() {
        final var definitionFromDdl = unionIndexDefinition();

        // The index as it was before member `workshop` was added.
        replaceUnionIndex("CASE WHEN LOCATION__WAGONSLOT IS NOT NULL THEN LOCATION__WAGONSLOT END", "ASC");
        assertThat(upgrade.findOutdated())
                .extracting(IComputedUnionColumnUpgrade.OutdatedUnionIndex::entityType, IComputedUnionColumnUpgrade.OutdatedUnionIndex::property,
                            IComputedUnionColumnUpgrade.OutdatedUnionIndex::unionType, IComputedUnionColumnUpgrade.OutdatedUnionIndex::problem)
                .containsExactly(tuple(TgBogie.class, TgBogie.LOCATION, TgBogieLocation.class, OUTDATED));

        exec(upgrade.createSql().property(TgBogie.class, TgBogie.LOCATION));
        assertThat(unionIndexDefinition()).isNotEqualTo(definitionFromDdl);

        exec(upgrade.dropSql().propertiesWithType(TgBogieLocation.class));
        exec(upgrade.createSql().propertiesWithType(TgBogieLocation.class));

        assertThat(unionIndexDefinition()).isEqualTo(definitionFromDdl);
        assertThat(upgrade.findOutdated()).isEmpty();
    }

    @Test
    @WithDbVersion({POSTGRESQL, MSSQL})
    public void after_a_member_is_removed_the_drop_script_allows_dropping_its_column_and_the_create_script_restores_the_definition_produced_by_the_current_DDL() {
        final var definitionFromDdl = unionIndexDefinition();

        try {
            // The index as it was before a third member was removed.
            exec("ALTER TABLE %s ADD %s BIGINT NULL".formatted(BOGIE_TABLE, REMOVED_MEMBER_COLUMN));
            replaceUnionIndex("CASE WHEN %1$s IS NOT NULL THEN %1$s WHEN LOCATION__WAGONSLOT IS NOT NULL THEN LOCATION__WAGONSLOT WHEN LOCATION__WORKSHOP IS NOT NULL THEN LOCATION__WORKSHOP END"
                              .formatted(REMOVED_MEMBER_COLUMN), "ASC");

            exec(upgrade.dropSql().propertiesWithType(TgBogieLocation.class));
            exec("ALTER TABLE %s DROP COLUMN %s".formatted(BOGIE_TABLE, REMOVED_MEMBER_COLUMN));
            exec(upgrade.createSql().propertiesWithType(TgBogieLocation.class));

            assertThat(unionIndexDefinition()).isEqualTo(definitionFromDdl);
            assertThat(upgrade.findOutdated()).isEmpty();
        } finally {
            dropUnionIndex();
            dropColumnIfExists(REMOVED_MEMBER_COLUMN);
        }
    }

    // :::::::::::::::::::::::: Detection of missing and outdated indexes ::::::::::::::::::::::::

    @Test
    @WithDbVersion({POSTGRESQL, MSSQL})
    public void nothing_is_outdated_in_a_database_created_with_the_current_DDL() {
        assertThat(upgrade.findOutdated()).isEmpty();
    }

    @Test
    @WithDbVersion({POSTGRESQL, MSSQL})
    public void a_dropped_index_is_reported_as_missing() {
        dropUnionIndex();
        assertThat(upgrade.findOutdated())
                .extracting(IComputedUnionColumnUpgrade.OutdatedUnionIndex::entityType, IComputedUnionColumnUpgrade.OutdatedUnionIndex::property,
                            IComputedUnionColumnUpgrade.OutdatedUnionIndex::problem)
                .containsExactly(tuple(TgBogie.class, TgBogie.LOCATION, MISSING));
    }

    @Test
    @WithDbVersion({POSTGRESQL, MSSQL})
    public void an_index_with_members_in_a_different_order_is_reported_as_outdated() {
        replaceUnionIndex("CASE WHEN LOCATION__WORKSHOP IS NOT NULL THEN LOCATION__WORKSHOP WHEN LOCATION__WAGONSLOT IS NOT NULL THEN LOCATION__WAGONSLOT END", "ASC");
        assertThat(upgrade.findOutdated())
                .extracting(IComputedUnionColumnUpgrade.OutdatedUnionIndex::property, IComputedUnionColumnUpgrade.OutdatedUnionIndex::problem)
                .containsExactly(tuple(TgBogie.LOCATION, OUTDATED));
    }

    @Test
    @WithDbVersion({POSTGRESQL, MSSQL})
    public void a_descending_index_is_reported_as_outdated() {
        replaceUnionIndex("CASE WHEN LOCATION__WAGONSLOT IS NOT NULL THEN LOCATION__WAGONSLOT WHEN LOCATION__WORKSHOP IS NOT NULL THEN LOCATION__WORKSHOP END", "DESC");
        assertThat(upgrade.findOutdated())
                .extracting(IComputedUnionColumnUpgrade.OutdatedUnionIndex::property, IComputedUnionColumnUpgrade.OutdatedUnionIndex::problem)
                .containsExactly(tuple(TgBogie.LOCATION, OUTDATED));
    }

    @Test
    @WithDbVersion({POSTGRESQL, MSSQL})
    public void an_index_with_a_branch_that_yields_a_member_other_than_the_one_it_tests_is_reported_as_outdated() {
        replaceUnionIndex("CASE WHEN LOCATION__WAGONSLOT IS NOT NULL THEN LOCATION__WORKSHOP WHEN LOCATION__WORKSHOP IS NOT NULL THEN LOCATION__WORKSHOP END", "ASC");
        assertThat(upgrade.findOutdated())
                .extracting(IComputedUnionColumnUpgrade.OutdatedUnionIndex::property, IComputedUnionColumnUpgrade.OutdatedUnionIndex::problem)
                .containsExactly(tuple(TgBogie.LOCATION, OUTDATED));
    }

    @Test
    @WithDbVersion({POSTGRESQL, MSSQL})
    public void a_reported_index_is_printed_as_its_property_union_type_problem_and_details() {
        final var outdated = new IComputedUnionColumnUpgrade.OutdatedUnionIndex(TgBogie.class, TgBogie.LOCATION, TgBogieLocation.class, OUTDATED, "Some details.");
        assertThat(outdated).hasToString("TgBogie.location (TgBogieLocation): OUTDATED — Some details.");
    }

    // :::::::::::::::::::::::: Helpers ::::::::::::::::::::::::

    /// Returns the definition of the index (and, for SQL Server, the computed column) for `TgBogie.location`, as recorded in the database catalog.
    /// The result is empty if the index does not exist.
    ///
    private List<String> unionIndexDefinition() {
        return switch (dbVersion) {
            case POSTGRESQL -> query("SELECT indexdef FROM pg_indexes WHERE schemaname = current_schema() AND indexname = '%s'"
                                     .formatted(BOGIE_LOCATION_INDEX.toLowerCase(ROOT)));
            case MSSQL -> query("""
                                SELECT c.name, c.definition, c.is_persisted, i.name, i.type_desc, i.is_unique, ic.key_ordinal, ic.is_descending_key
                                FROM sys.computed_columns c
                                JOIN sys.index_columns ic ON ic.object_id = c.object_id AND ic.column_id = c.column_id
                                JOIN sys.indexes i ON i.object_id = ic.object_id AND i.index_id = ic.index_id
                                WHERE c.object_id = OBJECT_ID('%s') AND c.name = '%s'
                                """.formatted(BOGIE_TABLE, BOGIE_LOCATION_COLUMN));
            default -> throw unexpectedDbVersion();
        };
    }

    /// Returns the names of all indexes on union expressions in the test database.
    ///
    private Set<String> unionIndexNamesInDatabase() {
        final var names = switch (dbVersion) {
            // PostgreSQL records the indexed expression across several lines, e.g., `((\nCASE\n    WHEN (...) THEN ...`.
            case POSTGRESQL -> query("SELECT indexname FROM pg_indexes WHERE schemaname = current_schema() AND indexdef ~ '\\(\\(\\s*CASE\\s+WHEN'");
            case MSSQL -> query("""
                                SELECT i.name
                                FROM sys.computed_columns c
                                JOIN sys.index_columns ic ON ic.object_id = c.object_id AND ic.column_id = c.column_id
                                JOIN sys.indexes i ON i.object_id = ic.object_id AND i.index_id = ic.index_id
                                """);
            default -> throw unexpectedDbVersion();
        };
        return upperCaseSet(names);
    }

    /// Returns the names of the union indexes for all persistent properties of the specified union type, determined by reflection over the domain.
    ///
    private Set<String> unionIndexNamesForPropertiesOfType(final Class<?> unionType) {
        final var extractor = new ColumnDefinitionExtractor(getInstance(HibernateTypeMappings.class), HibernateHelpers.getDialect(dbVersion));
        final var names = getInstance(IApplicationDomainProvider.class).entityTypes().stream()
                .filter(entityType -> isPersistentEntityType(entityType))
                .flatMap(entityType -> findRealProperties(entityType, MapTo.class).stream()
                        .filter(field -> field.getType() == unionType)
                        .map(field -> TableDdl.indexName(new TableDdl(extractor, entityType).getTableName(), mkColumnName(entityType, field.getName()))))
                .toList();
        return upperCaseSet(names);
    }

    private void dropUnionIndex() {
        switch (dbVersion) {
            case POSTGRESQL -> exec("DROP INDEX IF EXISTS %s".formatted(BOGIE_LOCATION_INDEX));
            case MSSQL -> {
                exec("DROP INDEX IF EXISTS %s ON %s".formatted(BOGIE_LOCATION_INDEX, BOGIE_TABLE));
                dropColumnIfExists(BOGIE_LOCATION_COLUMN);
            }
            default -> throw unexpectedDbVersion();
        }
    }

    private void dropColumnIfExists(final String column) {
        exec(switch (dbVersion) {
            case POSTGRESQL -> "ALTER TABLE %s DROP COLUMN IF EXISTS %s".formatted(BOGIE_TABLE, column);
            case MSSQL -> "IF COL_LENGTH('%1$s', '%2$s') IS NOT NULL ALTER TABLE %1$s DROP COLUMN %2$s".formatted(BOGIE_TABLE, column);
            default -> throw unexpectedDbVersion();
        });
    }

    /// Replaces the index (and, for SQL Server, the computed column) for `TgBogie.location` with one on the specified expression and in the specified order.
    ///
    private void replaceUnionIndex(final String expression, final String order) {
        dropUnionIndex();
        switch (dbVersion) {
            case POSTGRESQL -> exec("CREATE INDEX %s ON %s((%s) %s)".formatted(BOGIE_LOCATION_INDEX, BOGIE_TABLE, expression, order));
            case MSSQL -> {
                exec("ALTER TABLE %s ADD %s AS (%s)".formatted(BOGIE_TABLE, BOGIE_LOCATION_COLUMN, expression));
                exec("CREATE INDEX %s ON %s(%s %s)".formatted(BOGIE_LOCATION_INDEX, BOGIE_TABLE, BOGIE_LOCATION_COLUMN, order));
            }
            default -> throw unexpectedDbVersion();
        }
    }

    /// Recreates the index (and, for SQL Server, the computed column) for `TgBogie.location` using the statements of the current DDL.
    ///
    private void resetUnionIndexToCurrentDdl() {
        final var dialect = HibernateHelpers.getDialect(dbVersion);
        final var ddl = new TableDdl(new ColumnDefinitionExtractor(getInstance(HibernateTypeMappings.class), dialect), TgBogie.class);
        dropUnionIndex();
        switch (dbVersion) {
            case POSTGRESQL -> ddl.createIndicesSchema(List.of(BOGIE_LOCATION_INDEX)).forEach(this::exec);
            case MSSQL -> {
                final var column = ddl.getColumnDefinition(TgBogie.LOCATION);
                exec("ALTER TABLE %s ADD %s".formatted(BOGIE_TABLE, column.schemaString(dialect)));
                ddl.createIndicesSchema(column).forEach(this::exec);
            }
            default -> throw unexpectedDbVersion();
        }
        assertThat(unionIndexDefinition()).as("The union index should be recreated from the current DDL.").isNotEmpty();
    }

    /// Maps the name of each index created by the specified script to the name of its table, both in upper case.
    ///
    private static Map<String, String> createdIndexes(final String sql) {
        return CREATE_INDEX.matcher(sql).results()
                .collect(Collectors.toMap(match -> match.group(1).toUpperCase(ROOT), match -> match.group(2).toUpperCase(ROOT),
                                          (earlier, later) -> later, TreeMap::new));
    }

    /// Returns the names of the indexes dropped by the specified script, in upper case.
    ///
    private static Set<String> droppedIndexes(final String sql) {
        return DROP_INDEX.matcher(sql).results()
                .map(match -> match.group(1).toUpperCase(ROOT))
                .collect(Collectors.toCollection(TreeSet::new));
    }

    private static Set<String> upperCaseSet(final List<String> values) {
        return values.stream()
                .map(value -> value.toUpperCase(ROOT))
                .collect(Collectors.toCollection(TreeSet::new));
    }

    private void exec(final String sql) {
        transactionally(conn -> {
            try (final var stmt = conn.createStatement()) {
                stmt.execute(sql);
                return null;
            } catch (final SQLException ex) {
                throw new IllegalStateException(ex);
            }
        });
    }

    /// Returns the rows produced by the specified query, each with the values of its columns separated by ` | `.
    ///
    private List<String> query(final String sql) {
        return transactionally(conn -> {
            try (final var stmt = conn.createStatement(); final var rs = stmt.executeQuery(sql)) {
                final var columnCount = rs.getMetaData().getColumnCount();
                final var result = new ArrayList<String>();
                while (rs.next()) {
                    final var row = new ArrayList<String>(columnCount);
                    for (int column = 1; column <= columnCount; column++) {
                        row.add(rs.getString(column));
                    }
                    result.add(String.join(" | ", row));
                }
                return result;
            } catch (final SQLException ex) {
                throw new IllegalStateException(ex);
            }
        });
    }

    private <R> R transactionally(final Function<Connection, R> action) {
        return getInstance(TransactionalExecution.class).execFn(action);
    }

    private IllegalStateException unexpectedDbVersion() {
        return new IllegalStateException("Unexpected database [%s].".formatted(dbVersion));
    }

}
